"""Evaluation on real datasets: python src/eval/measure.py → src/eval/results.md (every number is computed here).

Analyses every readable file in data/raw. Files over MAX_POSTS posts are cut to the 6 hours around their busiest hour,
where many accounts are active together. Text-only files (no account or time) are listed as not analysable.
"""
import sys
import time
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

SRC_DIR = Path(__file__).resolve().parents[1]
if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

from config import DATA, RAW
from engine.normalize import MissingColumns, load_posts
from engine.pipeline import analyze
from engine.schema import Post

MAX_POSTS = 60_000
TYPES = (".csv", ".tsv", ".xlsx", ".json", ".jsonl", ".ndjson", ".txt")


def busiest_window(posts: list[Post], hours: int = 6) -> list[Post]:
    """Research archives are grouped by account, so the first N rows hold only a few accounts.
    Take the posts around the busiest hour instead, where many accounts are active together."""
    peak = Counter(p.created_at // 3600 for p in posts).most_common(1)[0][0] * 3600
    half = hours * 3600 // 2
    return [p for p in posts if peak - half <= p.created_at < peak + half]


def run(path: Path) -> dict:
    t0 = time.perf_counter()
    try:
        all_posts = load_posts(path)
    except MissingColumns:
        return {"file": path.name, "skipped": "text and labels only, no account or time columns"}
    posts = all_posts if len(all_posts) <= MAX_POSTS else busiest_window(all_posts)
    res = analyze(dataset_id=f"eval_{path.stem}", posts=posts, output_dir=DATA / "eval")
    camps = res["campaigns"]
    out = {
        "file": path.name,
        "rows": len(all_posts),
        "window": "whole file" if posts is all_posts else
                  "6 h from " + datetime.fromtimestamp(min(p.created_at for p in posts), timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        "posts": len(posts), "accounts": res["accounts"], "campaigns": len(camps),
        "clustered": sum(c["size"] for c in camps), "scores": [c["score"] for c in camps],
        "signals": sorted({s for c in camps for s in c["signals"]}),
        "languages": [l for l, _ in Counter(p.language for p in posts if p.language).most_common(3)],
        "runtime_s": round(time.perf_counter() - t0, 1),
    }
    print(f"  - {path.name}: {out['campaigns']} campaigns, {out['clustered']} accounts, scores {out['scores']}")
    return out


def row(r: dict) -> str:
    if "skipped" in r:
        return f"| `{r['file']}` | not analysable: {r['skipped']} | | | | | | |"
    return (f"| `{r['file']}` | {r['rows']:,} rows → {r['posts']:,} posts, {r['accounts']:,} accounts ({r['window']}) | "
            f"{', '.join(r['languages']) or '—'} | {r['campaigns']} | {r['clustered']} | "
            f"{', '.join(map(str, r['scores'])) or '—'} | {', '.join(r['signals']) or '—'} | {r['runtime_s']} s |")


def run_evaluation():
    files = sorted(p for p in RAW.glob("*") if p.suffix.lower() in TYPES) if RAW.exists() else []
    print(f"Analysing {len(files)} files in {RAW}...")
    results = [run(p) for p in files]
    results_md = f"""# Evaluation Results

Generated by `python src/eval/measure.py` on {datetime.now().strftime("%d %B %Y")}. Every number below is computed by that script,
on every readable file in `data/raw` (real datasets; see `docs/setup-guide.md` for where to download them).

Files over {MAX_POSTS:,} posts are cut to the 6 hours around their busiest hour, when many accounts post together (the
archives are grouped by account, so the first rows would hold only a handful of accounts).

| File | Input | Main languages | Campaigns | Accounts clustered | CIB scores | Signals | Time |
|---|---|---|---|---|---|---|---|
{chr(10).join(map(row, results))}

These datasets have no ground truth, so the table shows what was found, not accuracy. The score weights were set by hand
and are not yet calibrated on labelled real data. Research archives lack some fields (the IRA file has no account creation
dates or retweet targets), so some signals cannot fire there.
"""
    path = SRC_DIR / "eval" / "results.md"
    path.write_text(results_md, encoding="utf-8")
    print(f"Results saved to {path}")


if __name__ == "__main__":
    run_evaluation()
